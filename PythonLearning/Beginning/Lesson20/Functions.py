# 1. Use Defined Functions:
def greet():          # define the function
    print("Hello, World!!!")


greet()     # call the function
print(greet())   # printing "Hello World!!",   None (data Types)

# 2. Parameters vs arguments

def greet(name):    # Function taking one input - parameters
    print("Hello", name)

greet("Akku")  # argument - value you are passing to Parameters