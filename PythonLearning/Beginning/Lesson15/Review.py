#The while Loop
#---------------------
#With the while loop we can execute a set of statements as long as a condition is true.
# Example1: Print Hello World - 3 times

count = 0

while count < 3:
    print("Hello, World!")
    count += 1    # count = count + 1

# Answer: Hello, World!
#Ietration1:  count = 0    0<3      print the value       count = 0 + 1  = 1  (1)
#Iteration2:  count =1     1<3